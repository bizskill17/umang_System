    pg.evaluate("location.hash='leads.add'"); pg.wait_for_timeout(150)
    pg.click('#lead-form button[type=submit]'); pg.wait_for_timeout(50)
    print("req err:", pg.inner_text("#lf_firm_id-err"))
    def fill_lead(cust, assign=None, est=None):
        pg.select_option("#lf_firm_id",label="Umang Communications"); pg.select_option("#lf_customer_id",label=cust)
        pg.select_option("#lf_lead_category_id",label="Signage"); pg.wait_for_timeout(30)
        pg.select_option("#lf_lead_subcategory_id",label="Glow Sign"); pg.select_option("#lf_lead_source_id",label="Referral")
        pg.select_option("#lf_owner_id",label="Ravi Kumar")
        if assign: pg.select_option("#lf_assigned_to",label=assign)
        if est: pg.fill("#lf_estimate",est)
        pg.click('#lead-form button[type=submit]'); pg.wait_for_timeout(150)
    fill_lead("Acme Retail")
    print("after add hash:", pg.evaluate("location.hash"), "|", pg.inner_text(".mv-note.ok"))
    pg.evaluate("location.hash='leads.add'"); pg.wait_for_timeout(100)
    fill_lead("Bright Malls", assign="Sita Rao", est="250000")
    print("in progress:\n ", pg.inner_text(".lead-table tbody").replace("\n","\n  "))
    # pending assignee
    pg.evaluate("location.hash='leads.pending-assignee'"); pg.wait_for_timeout(100)
    pg.select_option("select[data-assign]", label="Ravi Kumar"); pg.click('[data-act="save-assign"]'); pg.wait_for_timeout(150)
    print("assign msg:", pg.inner_text(".mv-note.ok"))
    pg.evaluate("location.hash='leads.pending-estimate'"); pg.wait_for_timeout(100)
    pg.fill("input[data-est]","120000"); pg.click('[data-act="save-est"]'); pg.wait_for_timeout(150)
    print("est msg:", pg.inner_text(".mv-note.ok"))
    pg.evaluate("location.hash='leads.pending-follow-ups'"); pg.wait_for_timeout(120)
    print("follow-ups rows:", pg.eval_on_selector_all(".lead-table tbody tr","els=>els.map(e=>e.className+':'+e.cells[0].innerText)"))
    pg.screenshot(path=f"{out}/fu-list.png")
    pg.click('.lead-table [data-act="fu"] >> nth=0'); pg.wait_for_timeout(100)
