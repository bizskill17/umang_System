import sys
from playwright.sync_api import sync_playwright
src,out=sys.argv[1],sys.argv[2]
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={"width":1366,"height":900}); errs=[]; pg.on("pageerror",lambda e:errs.append(str(e)))
    pg.goto("file://"+src); pg.fill("#login-email","admin"); pg.fill("#login-password","x"); pg.click(".login-btn"); pg.wait_for_timeout(100)
    def addm(h,vals):
        pg.evaluate(f"location.hash='{h}'"); pg.wait_for_timeout(120)
        for v in vals:
            pg.click('[data-act="add"]')
            for k,val in v.items():
                if k.startswith("sel:"): pg.select_option("#mf-"+k[4:], label=val)
                else: pg.fill("#mf-"+k,val)
            pg.click('#mv-form button[type=submit]'); pg.wait_for_timeout(60)
    addm("leads.m-firm",[{"name":"Umang Communications","short_name":"UMANG"}])
    addm("leads.m-customers",[{"name":"Acme Retail"},{"name":"Bright Malls"}])
    addm("leads.m-lead-category",[{"name":"Signage"}])
    addm("leads.m-lead-subcategory",[{"sel:lead_category_id":"Signage","name":"Glow Sign"}])
    addm("leads.m-lead-sources",[{"name":"Referral"}])
    addm("leads.m-users",[{"name":"Ravi Kumar","email":"ravi@x.in"},{"name":"Sita Rao","email":"sita@x.in"}])
